"""Generate PPC_FUNC stubs for every kernel/XAM/Net/Vd/XAudio import the recompiled
code references, so the port links. Real implementations replace these in Phase 2.
Scans re/ppc for __imp__<Name> symbols that are NOT __imp__sub_ (those are game funcs)."""
import re, os, glob

PPC = r"D:\Projects\Tekken Tag Tournament 2 (USA, Europe)\re\ppc"
OUT = r"D:\Projects\Tekken Tag Tournament 2 (USA, Europe)\port\src\runtime\kernel_stubs.gen.cpp"

RUNTIME = r"D:\Projects\Tekken Tag Tournament 2 (USA, Europe)\port\src\runtime"

# Functions with real hand-written implementations must NOT get a stub (would duplicate-define).
impl_pat = re.compile(rb"PPC_FUNC\(__imp__([A-Za-z0-9_]+)\)")
implemented = set()
for f in glob.glob(os.path.join(RUNTIME, "**", "*.cpp"), recursive=True):
    if os.path.basename(f).endswith(".gen.cpp"):
        continue
    with open(f, "rb") as fh:
        for m in impl_pat.finditer(fh.read()):
            implemented.add(m.group(1).decode())

pat = re.compile(rb"__imp__([A-Za-z0-9_]+)")
imports = set()
scan = glob.glob(os.path.join(PPC, "ppc_recomp.*.cpp")) + [os.path.join(PPC, "ppc_func_mapping.cpp")]
for f in scan:
    with open(f, "rb") as fh:
        for m in pat.finditer(fh.read()):
            name = m.group(1).decode()
            # skip game functions (__imp__sub_XXXX), the entry alias, and anything implemented for real
            if name.startswith("sub_") or name == "_xstart" or name in implemented:
                continue
            imports.add(name)
print(f"({len(implemented)} imports implemented for real, excluded from stubs)")

imports = sorted(imports)
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w") as g:
    g.write("// AUTO-GENERATED by port/tools/gen_kernel_stubs.py -- do not edit.\n")
    g.write("// One logging stub per Xbox 360 import used by TTT2. Replaced by real impls in Phase 2.\n")
    g.write('#include "ppc_recomp_shared.h"\n')
    g.write('#include "kernel_trace.h"\n\n')
    for name in imports:
        g.write(f"PPC_FUNC(__imp__{name}) {{ KernelStub(\"{name}\"); ctx.r3.u64 = 0; }}\n")
    g.write(f"\n// {len(imports)} import stubs\n")

print(f"generated {len(imports)} kernel stubs -> {OUT}")
